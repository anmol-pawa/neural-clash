// Embeds lib/py/*.py as TS string modules so the worker can mount them without a loader.
import { readFileSync, writeFileSync } from "node:fs";
for (const name of ["nc_test"]) {
  const src = readFileSync(`lib/py/${name}.py`, "utf8");
  writeFileSync(`lib/py/${name}.py.gen.ts`, `// generated by scripts/gen-py-sources.mjs from ${name}.py — do not edit\nexport const ${name.toUpperCase()}_PY = ${JSON.stringify(src)};\n`);
}
