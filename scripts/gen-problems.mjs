// Bundles content/problems/* into lib/dojo/problems.gen.ts for the Code Dojo (statement, hints, editorial,
// starter, sample + hidden tests). Expected outputs come from the native reference (g++), never typed by hand.
// The perf group is generated at meta.browserPerfN (smaller than the native verify run) to keep the bundle small.
// Usage: node scripts/gen-problems.mjs [--check]
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { findPython } from "./content-verify.mjs";

const root = "content/problems";
const sh = (cmd, args, opts = {}) => spawnSync(cmd, args, { encoding: "utf8", maxBuffer: 64 << 20, ...opts });

export function buildProblems() {
  const python = findPython();
  const tmp = mkdtempSync(join(tmpdir(), "nc-gen-problems-"));
  try {
    return readdirSync(root, { withFileTypes: true })
      .filter((d) => d.isDirectory() && existsSync(join(root, d.name, "meta.json")))
      .map((d) => {
        const dir = join(root, d.name);
        const meta = JSON.parse(readFileSync(join(dir, "meta.json"), "utf8"));
        const bin = join(tmp, meta.id);
        const c = sh("g++", ["-std=c++17", "-O2", join(dir, "solution.cpp"), "-o", bin]);
        if (c.status !== 0) throw new Error(`${meta.id}: reference does not compile`);
        const cases = (group, label, env = {}) =>
          (meta.groups[group] ?? []).map((seed) => {
            const g = sh(python, ["-I", join(dir, "gen.py"), group, String(seed)], { env: { ...process.env, ...env } });
            if (g.status !== 0) throw new Error(`${meta.id}: generator failed for ${group}/${seed}`);
            const r = sh(bin, [], { input: g.stdout });
            if (r.status !== 0) throw new Error(`${meta.id}: reference crashed on ${group}/${seed}`);
            return { name: `${label} ${seed}`, input: g.stdout, expected: r.stdout.trim() };
          });
        const perfEnv = meta.browserPerfN ? { NC_PERF_N: String(meta.browserPerfN) } : {};
        return {
          id: meta.id,
          title: meta.title,
          difficulty: meta.difficulty,
          tags: meta.tags,
          similar: meta.similar,
          timeLimitMs: meta.timeLimitMs,
          complexity: meta.complexity,
          hints: meta.hints,
          strategy: meta.strategy,
          statement: readFileSync(join(dir, "statement.md"), "utf8"),
          editorial: readFileSync(join(dir, "editorial.md"), "utf8"),
          starter: readFileSync(join(dir, "starter.cpp"), "utf8"),
          ...(existsSync(join(dir, "starter.py")) ? { starterPy: readFileSync(join(dir, "starter.py"), "utf8") } : {}),
          sample: cases("sample", "sample"),
          hidden: [...cases("edge", "edge"), ...cases("random", "random"), ...cases("perf", "perf", perfEnv).slice(0, 1)],
        };
      })
      .sort((a, b) => a.id.localeCompare(b.id));
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

const out = "lib/dojo/problems.gen.ts";
const text = `// generated by scripts/gen-problems.mjs from content/problems — do not edit\nimport type { DojoProblem } from "./catalog";\nexport const DOJO_PROBLEMS: DojoProblem[] = ${JSON.stringify(buildProblems())};\n`;
if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
    console.error("lib/dojo/problems.gen.ts is stale: run node scripts/gen-problems.mjs");
    process.exit(1);
  }
} else writeFileSync(out, text);
