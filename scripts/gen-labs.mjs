// Bundles content/labs/* (without reference solutions or wrong versions) into lib/labs/labs.gen.ts.
// Hidden tests are renamed test_hidden_* so the panel masks their failing values.
// Usage: node scripts/gen-labs.mjs [--check]
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = "content/labs";
const PHASE_ORDER = ["python-port", "vector-vale", "forge", "peaks", "grove"];
const read = (id, f) => readFileSync(join(root, id, f), "utf8");

export function buildLabs() {
  const labs = readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(root, d.name, "meta.json")))
    .map((d) => {
      const meta = JSON.parse(read(d.name, "meta.json"));
      const hidden = read(d.name, "tests_hidden.py").replace(/^def test_(?!hidden_)/gm, "def test_hidden_");
      return {
        id: meta.id,
        title: meta.title,
        phase: meta.phase,
        functions: meta.functions ?? [],
        hints: meta.hints ?? [],
        lesson: read(d.name, "lesson.md"),
        spec: read(d.name, "spec.py"),
        visibleTests: read(d.name, "tests_visible.py"),
        hiddenTests: hidden,
      };
    });
  labs.sort((a, b) => PHASE_ORDER.indexOf(a.phase) - PHASE_ORDER.indexOf(b.phase) || a.id.localeCompare(b.id));
  return labs;
}

const out = "lib/labs/labs.gen.ts";
const text = `// generated by scripts/gen-labs.mjs from content/labs — do not edit\nimport type { LabSource } from "./catalog";\nexport const LAB_SOURCES: LabSource[] = ${JSON.stringify(buildLabs(), null, 1)};\n`;
if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
    console.error("lib/labs/labs.gen.ts is stale: run node scripts/gen-labs.mjs");
    process.exit(1);
  }
} else writeFileSync(out, text);
